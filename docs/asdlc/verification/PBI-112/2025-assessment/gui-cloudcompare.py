def read_las(filename):
    b = (BUILD / filename).read_bytes()
    assert hashlib.sha256(b).hexdigest() == inspection[filename]['sha256']
    off = struct.unpack_from('<I', b, 96)[0]
    fmt, stride, count = struct.unpack_from('<BHI', b, 104)
    assert fmt == 3 and stride == 34
    scales = np.array(struct.unpack_from('<3d', b, 131))
    offsets = np.array(struct.unpack_from('<3d', b, 155))
    dtype = np.dtype({'names':['x','y','z','intensity','return_bits','class_bits','scan','user','psid','gps','r','g','b'],
       'formats':['<i4','<i4','<i4','<u2','u1','u1','i1','u1','<u2','<f8','<u2','<u2','<u2'],
       'offsets':[0,4,8,12,14,15,16,17,18,20,28,30,32], 'itemsize':34})
    arr = np.frombuffer(b,dtype=dtype,count=count,offset=off)
    xyz = np.column_stack([arr['x'],arr['y'],arr['z']])*scales+offsets
    log['sources'][filename] = {'sha256':hashlib.sha256(b).hexdigest(),'count':count}
    return arr,xyz


def cloud(name, xyz, rgb=None):
    local = np.ascontiguousarray(xyz+SHIFT, dtype=np.float32)
    p = pycc.ccPointCloud(local[:,0],local[:,1],local[:,2])
    p.setName(name); p.setGlobalShift(*SHIFT); p.setPointSize(2)
    if rgb is not None:
        p.setColors(np.ascontiguousarray(rgb,dtype=np.uint8)); p.showColors(True)
    keep.append(p)
    return p


def scene(name, arr,xyz,mask, selected):
    group=pycc.ccHObject(name); root.addChild(group); keep.append(group)
    ids=np.flatnonzero(mask)
    for sid in np.unique(arr['psid'][ids]):
        ii=ids[arr['psid'][ids]==sid]
        rgb=np.column_stack([arr[c][ii] for c in ['r','g','b']])
        if rgb.max()>255: rgb=rgb/256
        p=cloud('PointSourceId '+str(sid)+' (no flight direction inference)',xyz[ii],rgb)
        for field,values in [('record_index',ii),('PointSourceId',arr['psid'][ii]),('Classification',arr['class_bits'][ii]&31),('class_flags',arr['class_bits'][ii]>>5),('ScanAngleRank',arr['scan'][ii]),('Intensity',arr['intensity'][ii])]:
            idx=p.addScalarField(field); sf=p.getScalarField(idx); sf.asArray()[:]=values; sf.computeMinAndMax()
        p.showSF(False); group.addChild(p)
    for k,m in enumerate(selected):
        pos=np.array([m['E'],m['N'],m['Z']])
        valid=((arr['class_bits']&31)!=7)&((arr['class_bits']&128)==0)
        d2=((xyz[:,:2]-pos[:2])**2).sum(axis=1); d2[~valid]=np.inf
        i=int(np.argmin(d2)); proxy=np.array([m['E'],m['N'],xyz[i,2]])
        color=[0,255,255] if m['source']=='TPN' else [255,100,220]
        for j,(kind,pt) in enumerate([('XYZ datum unknown',pos),('XY / nearest-Z proxy',proxy)]):
            p=cloud(m['object_id']+' '+m['source']+' '+m['measurement_id']+' '+kind,np.array([pt]),np.array([color])); p.setPointSize(10); group.addChild(p)
            label=pycc.cc2DLabel(); label.addPickedPoint(p,0); label.setName(p.getName()); label.setDisplayedIn2D(True); label.setCollapsed(True); label.displayPointLegend(False); label.setPosition(0.03 if k==0 else 0.52,0.07+0.09*j); label.setRelativeMarkerScale(0.5); label.setVisible(True); p.addChild(label); keep.append(label)
        log['markers'].append({'scene':name,**m,'nearest_record_index':i,'nearest_xyz':xyz[i].tolist(),'nearest_dxy':float(math.sqrt(d2[i])),'proxy_xyz':proxy.tolist()})
    CC.addToDB(group,False,False,False,False)
    group.setEnabled(False)
    return group


scenes=[]
