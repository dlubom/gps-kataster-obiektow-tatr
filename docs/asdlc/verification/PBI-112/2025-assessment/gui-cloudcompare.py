    full=scene(key+' full (class 7 and withheld excluded)',arr,xyz,valid,selected)
    scenes.append((key+'-full',full,xyz[valid].mean(axis=0),240 if key=='pod-wanta' else 125,202.5 if key=='pod-wanta' else 90))
    targets=[('detail',selected)] if key=='sniezna' else [(m['source'].lower(),[m]) for m in selected]
    for suffix,ms in targets:
        center=np.array([[m['E'],m['N']] for m in ms]).mean(axis=0)
        mask=valid & (np.abs(xyz[:,0]-center[0])<=15)&(np.abs(xyz[:,1]-center[1])<=15)
        group=scene(key+'-'+suffix+' 30m crop',arr,xyz,mask,ms)
        z=float(np.median(xyz[mask,2])); cen=np.r_[center,z]
        scenes.append((key+'-'+suffix,group,cen,40,202.5 if key=='pod-wanta' else 90))

    # A smaller raw-point crop makes the candidate neighbourhood inspectable.
    ms = selected
    tpn = next(m for m in ms if m['source']=='TPN')
    center=np.array([tpn['E'],tpn['N']])
    mask=valid & (np.abs(xyz[:,0]-center[0])<=5)&(np.abs(xyz[:,1]-center[1])<=5)
    group=scene(key+'-close 10m crop',arr,xyz,mask,ms if key=='sniezna' else [tpn])
    nearest=int(np.argmin(((xyz[:,:2]-center)**2).sum(axis=1)))
    cen=np.r_[center,xyz[nearest,2]+1]
    scenes.append((key+'-close',group,cen,18,202.5 if key=='pod-wanta' else 90))

