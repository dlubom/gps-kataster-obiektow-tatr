"""Build a browsable Markdown catalogue from fully validated source records."""

from __future__ import annotations

import re
from collections.abc import Iterable
from pathlib import Path
from shutil import rmtree
from tempfile import mkdtemp
from typing import Any
from urllib.parse import quote, urlsplit

from gps_kataster_obiektow_tatr.best_measurement import select_default_best_measurement_id
from gps_kataster_obiektow_tatr.data_loader import (
    CAVES_DIR_NAME,
    DEFAULT_DATA_DIR,
    OBJECTS_DIR_NAME,
    RELATIONS_DIR_NAME,
    REPO_ROOT,
    LoadedYamlRecord,
    load_dataset,
)
from gps_kataster_obiektow_tatr.validator import (
    ValidationIssue,
    has_errors,
    validate_loaded_dataset,
)

DEFAULT_CATALOG_DIR = REPO_ROOT / "build" / "catalog"
_GENERATED_MARKER = "<!-- generated by build_catalog_cards.py -->"
_MARKDOWN_PUNCTUATION = re.compile(r"([\\`*_\[\]<>#|&~])")
_MARKDOWN_BLOCK_START = re.compile(r"^(-|(?:\+|\d{1,9}[.)])(?=\s))")


class CatalogCardsValidationError(ValueError):
    """The input catalogue contains errors and cannot be published."""

    def __init__(self, issues: tuple[ValidationIssue, ...]) -> None:
        self.issues = issues
        super().__init__("Walidacja katalogu nie powiodła się.")


def build_catalog_cards(
    *,
    data_dir: Path = DEFAULT_DATA_DIR,
    output_dir: Path = DEFAULT_CATALOG_DIR,
    repo_root: Path = REPO_ROOT,
) -> Path:
    """Publish a fresh set of cards and return the path of its index."""

    data_dir = data_dir.resolve()
    if output_dir.is_symlink():
        raise ValueError(f"Katalog wynikowy jest dowiązaniem symbolicznym: {output_dir}")
    output_dir = output_dir.resolve()
    build_dir = (REPO_ROOT / "build").resolve()
    source_dirs = (
        data_dir,
        DEFAULT_DATA_DIR.resolve(),
        *(
            (data_dir / name).resolve()
            for name in (OBJECTS_DIR_NAME, CAVES_DIR_NAME, RELATIONS_DIR_NAME)
        ),
    )
    if any(_overlaps(output_dir, source_dir) for source_dir in source_dirs) or (
        _overlaps(output_dir, REPO_ROOT) and build_dir not in output_dir.parents
    ):
        raise ValueError(f"Katalog wynikowy koliduje z katalogiem źródeł: {output_dir}")

    loaded = load_dataset(data_dir)
    for record in loaded.records():
        source = record.path.resolve()
        if not source.is_relative_to(data_dir) and _overlaps(output_dir, source):
            raise ValueError(f"Katalog wynikowy koliduje z plikiem źródłowym: {output_dir}")
    dataset, issues = validate_loaded_dataset(loaded, data_dir=data_dir, repo_root=repo_root)
    if has_errors(issues):
        raise CatalogCardsValidationError(issues)

    objects = {record.data["id"]: record for record in dataset.objects}
    caves = {record.data["id"]: record for record in dataset.caves}
    source_root = repo_root.resolve()
    source_label = "Rekord YAML w repozytorium"
    if not data_dir.is_relative_to(source_root):
        source_root = data_dir
        source_label = "Rekord YAML względem katalogu danych"

    def source_ref(record: LoadedYamlRecord) -> str:
        path = record.path.relative_to(source_root).as_posix()
        if "`" in path:
            return f"{source_label} — {_text(path)}"
        return f"{source_label} — `{path}`"

    pages = {
        Path("index.md"): _render_index(objects, caves),
        **{
            Path("objects", f"{record_id}.md"): _render_object(record, caves, source_ref(record))
            for record_id, record in objects.items()
        },
        **{
            Path("caves", f"{record_id}.md"): _render_cave(record, objects, source_ref(record))
            for record_id, record in caves.items()
        },
    }
    _publish_pages(output_dir, pages)
    return output_dir / "index.md"


def _within(path: Path, directory: Path) -> bool:
    if path.is_relative_to(directory):
        return True
    if not directory.exists():
        return False
    return any(part.exists() and part.samefile(directory) for part in (path, *path.parents))


def _overlaps(left: Path, right: Path) -> bool:
    return _within(left, right) or _within(right, left)


def _check_generated_output(output_dir: Path) -> None:
    if not output_dir.is_dir() or output_dir.is_symlink():
        raise ValueError(f"Katalog wynikowy zawiera inne dane: {output_dir}")
    card_dirs = {output_dir / "objects", output_dir / "caves"}
    marker = (_GENERATED_MARKER + "\n").encode()
    for path in output_dir.rglob("*"):
        if not path.is_symlink():
            if path in card_dirs and path.is_dir():
                continue
            if path.is_file() and (
                path == output_dir / "index.md"
                or (path.parent in card_dirs and path.suffix == ".md")
            ):
                with path.open("rb") as stream:
                    if stream.read(len(marker)) == marker:
                        continue
        raise ValueError(f"Katalog wynikowy zawiera inne dane: {path}")


def _publish_pages(output_dir: Path, pages: dict[Path, str]) -> None:
    output_dir.parent.mkdir(parents=True, exist_ok=True)
    work_dir = Path(mkdtemp(prefix=f".{output_dir.name}-", dir=output_dir.parent))
    staged = work_dir / "new"
    backup = work_dir / "previous"
    try:
        for relative_path, contents in pages.items():
            path = staged / relative_path
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents, encoding="utf-8", newline="\n")

        if output_dir.exists():
            _check_generated_output(output_dir)
            output_dir.rename(backup)
        try:
            staged.rename(output_dir)
        except OSError:
            if backup.exists():
                backup.rename(output_dir)
            raise
        if backup.exists():
            rmtree(backup)
    finally:
        # A failed rollback must leave the previous catalogue recoverable.
        if not backup.exists():
            rmtree(work_dir)


def _text(value: Any, *, unknown: str = "—") -> str:
    if value is None or value == "":
        return unknown
    line = " ".join(str(value).splitlines()).replace("\t", " ").strip()
    escaped = _MARKDOWN_PUNCTUATION.sub(r"\\\1", line)
    return _MARKDOWN_BLOCK_START.sub(lambda match: match[1][:-1] + "\\" + match[1][-1], escaped)


def _relative_link(label: Any, relative: str) -> str:
    return f"[{_text(label)}]({quote(relative, safe='/')})"


def _record_label(record: LoadedYamlRecord, name_key: str) -> str:
    record_id = record.data["id"]
    name = record.data.get(name_key)
    return f"{record_id} — {name}" if name else record_id


def _render_index(objects: dict[str, LoadedYamlRecord], caves: dict[str, LoadedYamlRecord]) -> str:
    lines = [_GENERATED_MARKER, "", "# Katalog obiektów i jaskiń"]
    for title, directory, name_key, records in (
        ("Obiekty", "objects", "name_local", objects),
        ("Jaskinie", "caves", "name", caves),
    ):
        lines.extend(["", f"## {title} ({len(records)})", ""])
        for record_id, record in sorted(records.items()):
            link = _relative_link(_record_label(record, name_key), f"{directory}/{record_id}.md")
            lines.append(f"- {link}")
    return "\n".join(lines).rstrip() + "\n"


def _header(record: LoadedYamlRecord, name_key: str, source_ref: str) -> list[str]:
    return [
        _GENERATED_MARKER,
        "",
        f"# {_text(_record_label(record, name_key))}",
        "",
        "[Indeks](../index.md)",
        "",
        source_ref,
        "",
    ]


def _render_object(
    record: LoadedYamlRecord, caves: dict[str, LoadedYamlRecord], source_ref: str
) -> str:
    obj = record.data
    lines = _header(record, "name_local", source_ref)
    lines.append(f"- Kategoria — {_text(obj['category'])}")
    if cave_id := obj.get("cave_id"):
        cave_link = _relative_link(_record_label(caves[cave_id], "name"), f"../caves/{cave_id}.md")
        lines.append(f"- Jaskinia — {cave_link}")
    if notes := obj.get("notes"):
        lines.extend(["", "## Notatka o obiekcie", "", _text(notes)])

    best = obj["best_measurement"]
    selected = next(m for m in obj["measurements"] if m["id"] == best["measurement_id"])
    automatic_id = (
        select_default_best_measurement_id(obj["measurements"]) if best["mode"] == "auto" else None
    )
    mismatch = best["mode"] == "auto" and automatic_id != selected["id"]
    default_reason = (
        "Zapisane wskazanie w YAML; różni się od wyniku bieżącej reguły automatycznej."
        if mismatch
        else "Reguła automatyczna uwzględnia kolejno priorytet źródła i statusu, "
        "datę obserwacji, dokładność poziomą oraz identyfikator pomiaru."
    )
    reason = best.get("reason") or default_reason
    lines.extend(
        [
            "",
            "## Wybrany pomiar",
            "",
            f"- Pomiar — {_text(selected['id'])}",
            f"- Tryb — {_text(best['mode'])}",
            f"- Uzasadnienie — {_text(reason)}",
            "",
        ]
    )
    if mismatch:
        lines.extend(
            [
                f"- Wynik reguły automatycznej — {_text(automatic_id, unknown='brak')}",
                "- Ostrzeżenie — Zapisany wybór różni się od wyniku reguły automatycznej. "
                "Karta zachowuje zapisany pomiar; rozbieżność wymaga review.",
                "",
            ]
        )
    lines.extend(
        _table(
            ("Pole", "Wartość"),
            (
                ("Data obserwacji", _text(_observed(selected), unknown="nieznana")),
                ("Źródło", _text(selected["source"])),
                ("Identyfikator źródłowy", _text(selected.get("source_ref"))),
                ("Data źródła", _text(selected.get("source_date"), unknown="nieznana")),
                ("Metoda", _text(selected["method"])),
                ("Status weryfikacji", _text(selected["verification_status"])),
                ("WGS84 (szer., dł.)", _position(selected)),
                ("PUWG 1992 (x, y)", f"{_text(selected['x_1992'])}, {_text(selected['y_1992'])}"),
                ("Wysokość", _metres(selected.get("elevation_m"))),
                ("Źródło wysokości", _text(selected.get("elevation_source"), unknown="nieznane")),
                ("Datum wysokości", _datum(selected.get("elevation_datum"))),
                ("Dokładność pozioma", _metres(selected.get("horizontal_accuracy_m"))),
                ("Dokładność pionowa", _metres(selected.get("vertical_accuracy_m"))),
            ),
        )
    )
    lines.extend(_external_refs(obj["external_refs"]))
    lines.extend(["", "## Historia pomiarów", ""])
    lines.extend(
        _table(
            (
                "Pomiar",
                "Obserwacja",
                "Źródło",
                "Identyfikator źródłowy",
                "Metoda",
                "Status",
                "WGS84 (szer., dł.)",
                "Wysokość",
                "Datum wysokości",
                "Dokł. poz.",
                "Dokł. pion.",
                "Notatka",
            ),
            (
                (
                    _text(m["id"]),
                    _text(_observed(m), unknown="nieznana"),
                    _text(m["source"]),
                    _text(m.get("source_ref")),
                    _text(m["method"]),
                    _text(m["verification_status"]),
                    _position(m),
                    _metres(m.get("elevation_m")),
                    _datum(m.get("elevation_datum")),
                    _metres(m.get("horizontal_accuracy_m")),
                    _metres(m.get("vertical_accuracy_m")),
                    _text(m.get("notes")),
                )
                for m in obj["measurements"]
            ),
        )
    )
    return "\n".join(lines) + "\n"


def _render_cave(
    record: LoadedYamlRecord, objects: dict[str, LoadedYamlRecord], source_ref: str
) -> str:
    cave = record.data
    lines = _header(record, "name", source_ref)
    if system := cave.get("system_name"):
        lines.append(f"- System — {_text(system)}")
    if notes := cave.get("notes"):
        lines.extend(["", "## Notatka o jaskini", "", _text(notes)])
    lines.extend(_external_refs(cave["external_refs"]))
    lines.extend(["", "## Obiekty", ""])
    for object_id in cave["object_ids"]:
        link = _relative_link(
            _record_label(objects[object_id], "name_local"), f"../objects/{object_id}.md"
        )
        lines.append(f"- {link}")
    if not cave["object_ids"]:
        lines.append("Brak przypisanych obiektów.")
    return "\n".join(lines) + "\n"


def _external_refs(references: list[dict[str, Any]]) -> list[str]:
    if not references:
        return []
    lines = ["", "## Odniesienia źródłowe", ""]
    lines.extend(
        _table(
            ("System", "Typ", "Identyfikator", "Zakres", "Adres", "Notatka"),
            (
                (
                    _text(ref["system"]),
                    _text(ref["ref_type"]),
                    _text(ref["external_id"]),
                    _text(ref.get("scope")),
                    _url(ref.get("url")),
                    _text(ref.get("notes")),
                )
                for ref in references
            ),
        )
    )
    return lines


def _url(value: str | None) -> str:
    if value is None:
        return "—"
    try:
        parsed = urlsplit(value)
    except ValueError:
        return _text(value)
    if parsed.scheme in {"http", "https"} and parsed.netloc:
        # Preserve the displayed URL and encode Markdown delimiters in the target.
        target = quote(value, safe=":/?#[]@!$&'*+,;=%")
        return f"[{_text(value)}]({target})"
    return _text(value)


def _table(headers: tuple[str, ...], rows: Iterable[tuple[str, ...]]) -> list[str]:
    def row(cells: Iterable[str]) -> str:
        return "| " + " | ".join(cells) + " |"

    return [row(headers), row("---" for _ in headers), *(row(cells) for cells in rows)]


def _observed(measurement: dict[str, Any]) -> str | None:
    return measurement.get("observed_at") or measurement.get("observed_date")


def _position(measurement: dict[str, Any]) -> str:
    return f"{_text(measurement['lat'])}, {_text(measurement['lon'])}"


def _datum(value: str | None) -> str:
    return "nieznane" if value in (None, "unknown") else _text(value)


def _metres(value: int | float | None) -> str:
    return "nieznana" if value is None else f"{_text(value)} m"
